package com.mobiinfer.demo

import android.graphics.Bitmap

sealed class ChatMessage {
    abstract val id: Long

    data class UserMessage(
        override val id: Long,
        val text: String,
        val imageBitmap: Bitmap? = null,
        val imageInfo: String? = null,
        val isPrefilling: Boolean = false,
        // True when [imageBitmap] is a video's first frame and the
        // cell should overlay a play icon to communicate "this was a
        // video, the model saw N sampled frames".  Mirrors iOS
        // MBImageTableViewCell's video-playback overlay.
        val isVideo: Boolean = false,
        // Persisted reference to the picked media (a SAF content:// URI).
        // Stored instead of the bitmap so a saved conversation can re-open the
        // original file for display and for context replay. Null for synthetic
        // messages (e.g. restored placeholders) that carry no media.
        val imageUri: String? = null,
        // Set on the bubble that produced an ImageResult (text-to-image mode
        // or the generate_image tool). Those turns never go to the LLM as a
        // bare question without an answer; see ImagePromptMarker.
        val isImagePrompt: Boolean = false
    ) : ChatMessage()

    data class AiMessage(
        override val id: Long,
        val text: String,
        val isGenerating: Boolean = false,
        val metrics: InferenceMetrics? = null,
        // True while this bubble is only a "thinking" placeholder shown during
        // model loading (not an actual generation). Hides the stop button.
        val isLoadingPlaceholder: Boolean = false,
        // Set while this bubble is not being generated by the language model at
        // all: the image stack is drawing, so "thinking" is the wrong word and
        // the stop button must not pretend a stream is running.
        val waitingForImage: Boolean = false,
        // Display-only status line (e.g. "generating image: …"). It is never
        // part of the text sent back to the model.
        val status: String? = null
    ) : ChatMessage()

    /**
     * Assistant-side image result for a text-to-image turn. The bitmap is
     * decoded lazily by the view holder; [pngPath] is the file kept on disk so
     * a saved conversation can redraw it after a restart.
     */
    data class ImageResult(
        override val id: Long,
        val prompt: String,
        val pngPath: String?,
        // Size/steps/cfg/seed actually used, shown under the image.
        val paramsText: String?,
        val isGenerating: Boolean = false,
        val error: String? = null,
        val elapsedMs: Long? = null,
        // Set when the image was requested by the language model through the
        // generate_image tool rather than by the image-mode switch.
        val requestedByModel: Boolean = false,
        // 0..1 while generating. -1 means "unknown" (indeterminate spinner).
        val progress: Float = -1f,
        // Human readable stage, e.g. "理解提示词中…" or "第 3/8 步".
        val stage: String? = null,
        // Latest low-resolution preview of the latent, replaced every step.
        // In-memory only: it is a transient frame, never persisted.
        val previewBitmap: Bitmap? = null,
        // Display name of the checkpoint that actually draws the picture. With
        // the tool flow the selected model is the *language* model, so the
        // card used to be labelled "Qwen3-VL" while MOSS-Image was drawing.
        val imageModelName: String? = null
    ) : ChatMessage()

    data class WelcomeCard(
        override val id: Long = 0L,
        val isTextOnly: Boolean = false,
        // The home screen is currently in text-to-image mode, so the card
        // suggests image prompts instead of chat ones.
        val isImageMode: Boolean = false
    ) : ChatMessage()

    /**
     * Inline card shown in the chat stream when the user sends a request but the
     * selected model has not been downloaded yet.  It never uses a dialog: the
     * card itself offers the download confirmation and, once accepted, turns
     * into a progress indicator in place.
     */
    data class ModelDownloadPrompt(
        override val id: Long,
        val modelName: String,
        val downloading: Boolean = false,
        val paused: Boolean = false,
        val fraction: Float = 0f,
        val status: String? = null
    ) : ChatMessage()
}

data class InferenceMetrics(
    val imageProcessingMs: Long?,
    val prefillTokensPerSecond: Double?,
    val decodeTokensPerSecond: Double?,
    val totalMs: Long
)
